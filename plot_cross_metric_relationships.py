from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# Project folders
PROJECT_DIR = Path(__file__).resolve().parent

CORRELATION_DIR = PROJECT_DIR / "correlation_results"
OUTPUT_DIR = PROJECT_DIR / "visualization_results"

NIGHTLY_FILE = CORRELATION_DIR / "nightly_correlation_features.csv"
CORRELATION_FILE = CORRELATION_DIR / "nightly_correlations.csv"


# Friendly names used on plots
LABELS = {
    "total_sleep_time_min": "Total Sleep Time (min)",
    "deep_sleep_min": "Deep Sleep (min)",
    "rem_sleep_min": "REM Sleep (min)",
    "sleep_efficiency_percent": "Sleep Efficiency (%)",
    "observed_awakenings_count": "Observed Awakenings",
    "hr_average_bpm": "Average Heart Rate (bpm)",
    "hr_lowest_bpm": "Lowest Heart Rate (bpm)",
    "hrv_rmssd_ms": "HRV RMSSD (ms)",
    "temperature_delta_c": "Temperature Delta (°C)",
}


# Features to include in the heatmap
HEATMAP_FEATURES = [
    "total_sleep_time_min",
    "deep_sleep_min",
    "rem_sleep_min",
    "sleep_efficiency_percent",
    "observed_awakenings_count",
    "hr_average_bpm",
    "hr_lowest_bpm",
    "hrv_rmssd_ms",
    "temperature_delta_c",
]


def load_data():
    """Load the outputs generated by Issue #21."""

    if not NIGHTLY_FILE.exists():
        raise FileNotFoundError(
            f"Could not find {NIGHTLY_FILE}. "
            "Run nightly_correlations.py first."
        )

    if not CORRELATION_FILE.exists():
        raise FileNotFoundError(
            f"Could not find {CORRELATION_FILE}. "
            "Run nightly_correlations.py first."
        )

    nightly = pd.read_csv(NIGHTLY_FILE)
    correlations = pd.read_csv(CORRELATION_FILE)

    return nightly, correlations


def create_heatmap(correlations):
    """Create a heatmap using within-person correlations from Issue #21."""

    matrix = pd.DataFrame(
        np.nan,
        index=HEATMAP_FEATURES,
        columns=HEATMAP_FEATURES,
        dtype=float,
    )

    # A feature is perfectly correlated with itself
    for feature in HEATMAP_FEATURES:
        matrix.loc[feature, feature] = 1.0

    # Fill cross-metric correlations
    for _, row in correlations.iterrows():
        x = row["feature_x"]
        y = row["feature_y"]

        if x in HEATMAP_FEATURES and y in HEATMAP_FEATURES:
            r = row["within_r"]

            if pd.notna(r):
                matrix.loc[x, y] = r
                matrix.loc[y, x] = r

    fig, ax = plt.subplots(figsize=(11, 9))

    image = ax.imshow(
        matrix.values,
        vmin=-1,
        vmax=1,
        cmap="coolwarm",
    )

    display_labels = [LABELS[f] for f in HEATMAP_FEATURES]

    ax.set_xticks(range(len(display_labels)))
    ax.set_yticks(range(len(display_labels)))

    ax.set_xticklabels(display_labels, rotation=45, ha="right")
    ax.set_yticklabels(display_labels)

    # Write correlation values inside cells
    for i in range(len(HEATMAP_FEATURES)):
        for j in range(len(HEATMAP_FEATURES)):
            value = matrix.iloc[i, j]

            if pd.notna(value):
                ax.text(
                    j,
                    i,
                    f"{value:.2f}",
                    ha="center",
                    va="center",
                )

    ax.set_title("Cross-Metric Correlation Heatmap (Within-Person r)")

    colorbar = fig.colorbar(image, ax=ax)
    colorbar.set_label("Correlation (r)")

    fig.tight_layout()

    output_path = OUTPUT_DIR / "correlation_heatmap.png"
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)

    print(f"Created: {output_path}")


def find_correlation(correlations, x, y):
    """Find the correlation result for one feature pair."""

    match = correlations[
        ((correlations["feature_x"] == x) &
         (correlations["feature_y"] == y))
        |
        ((correlations["feature_x"] == y) &
         (correlations["feature_y"] == x))
    ]

    if match.empty:
        return np.nan, np.nan

    row = match.iloc[0]

    return row["pooled_pearson_r"], row["within_r"]


def create_scatterplot(
    nightly,
    correlations,
    x,
    y,
    filename,
):
    """Create one scatterplot using nightly observations."""

    pair = nightly[[x, y]].copy()

    pair[x] = pd.to_numeric(pair[x], errors="coerce")
    pair[y] = pd.to_numeric(pair[y], errors="coerce")

    # Use only nights where both values exist
    pair = pair.dropna()

    pooled_r, within_r = find_correlation(
        correlations,
        x,
        y,
    )

    fig, ax = plt.subplots(figsize=(8, 6))

    ax.scatter(
        pair[x],
        pair[y],
        alpha=0.35,
        s=20,
    )

    ax.set_xlabel(LABELS[x])
    ax.set_ylabel(LABELS[y])

    ax.set_title(
        f"{LABELS[x]} vs {LABELS[y]}"
    )

    # Show correlation information
    info = (
        f"Nights used: {len(pair)}\n"
        f"Pooled Pearson r: {pooled_r:.2f}\n"
        f"Within-person r: {within_r:.2f}"
    )

    ax.text(
        0.02,
        0.98,
        info,
        transform=ax.transAxes,
        verticalalignment="top",
    )

    ax.grid(alpha=0.2)

    fig.tight_layout()

    output_path = OUTPUT_DIR / filename
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)

    print(f"Created: {output_path}")


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    nightly, correlations = load_data()

    # Correlation heatmap
    create_heatmap(correlations)

    # Sleep vs Heart
    create_scatterplot(
        nightly,
        correlations,
        "deep_sleep_min",
        "hr_average_bpm",
        "deep_sleep_vs_average_hr.png",
    )

    # Temperature vs Heart
    create_scatterplot(
        nightly,
        correlations,
        "temperature_delta_c",
        "hr_average_bpm",
        "temperature_vs_average_hr.png",
    )

    # Sleep vs Temperature
    create_scatterplot(
        nightly,
        correlations,
        "total_sleep_time_min",
        "temperature_delta_c",
        "total_sleep_vs_temperature.png",
    )

    print("\nAll cross-metric plots generated successfully.")


if __name__ == "__main__":
    main()